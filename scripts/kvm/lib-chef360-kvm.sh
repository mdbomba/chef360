# MAC addresses are never entered by the operator. OS-image builds derive a
# deterministic 52:54:00 MAC from VM_IP; clone builds must prove uniqueness and
# regenerate when the derived address is already in use. resolve_vm_mac()
# persists the chosen address into PLAN.env so generate, deploy, and validate
# agree within a build.
generate_os_vm_mac() {
  local oct
  IFS=. read -r _ oct2 oct3 oct4 <<<"${VM_IP}"
  printf '52:54:00:%02x:%02x:%02x' "${oct2}" "${oct3}" "${oct4}"
}

generate_random_vm_mac() {
  local a b c
  a="$(openssl rand -hex 1)"
  b="$(openssl rand -hex 1)"
  c="$(openssl rand -hex 1)"
  printf '52:54:00:%s:%s:%s' "${a}" "${b}" "${c}"
}

# Return 0 when any defined libvirt domain other than ${ignore} uses ${mac}.
vm_mac_in_use() {
  local mac="$1" ignore="${2:--}" domain current
  while IFS= read -r domain; do
    [[ -n "${domain}" ]] || continue
    [[ "${domain}" != "${ignore}" ]] || continue
    current="$(virsh_system dumpxml "${domain}" 2>/dev/null | sed -n "s/.*mac address='\([0-9a-fA-F:]*\)'.*/\1/p" | head -1)"
    [[ -n "${current}" && "${current}" == "${mac}" ]] && return 0
  done < <(virsh_system list --all --name 2>/dev/null)
  return 1
}

persist_plan_value() {
  local key="$1" value="$2" plan="${CHEF360_PLAN_FILE:-${KVM_WORK_DIR}/${VM_NAME}-PLAN.env}"
  [[ -f "${plan}" ]] || return 0
  if grep -q "^${key}=" "${plan}"; then
    sed -i "s|^${key}=.*|${key}=${value}|" "${plan}"
  else
    printf '%s=%s\n' "${key}" "${value}" >>"${plan}"
  fi
  chmod 0600 "${plan}"
}

resolve_vm_mac() {
  if [[ -z "${VM_MAC:-}" ]]; then
    VM_MAC="$(generate_os_vm_mac)"
  fi
  local tries=0
  while vm_mac_in_use "${VM_MAC}" "${VM_NAME}"; do
    log_step "MAC ${VM_MAC} is already in use; regenerating for ${VM_NAME}"
    VM_MAC="$(generate_random_vm_mac)"
    tries=$((tries + 1))
    (( tries < 32 )) || fail "Unable to allocate a unique MAC for ${VM_NAME}"
  done
  persist_plan_value VM_MAC "${VM_MAC}"
  log_step "Resolved guest MAC: ${VM_MAC}"
}
