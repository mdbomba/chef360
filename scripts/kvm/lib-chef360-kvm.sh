#!/usr/bin/env bash

KVM_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${KVM_SCRIPT_DIR}/../.." && pwd)"
KVM_STATE_FILE="${KVM_CHEF360_STATE_FILE:-${PROJECT_ROOT}/config/kvm-chef360.env}"

# Capture explicitly-set source variables before the state file is sourced, so
# an explicit environment override always wins over the state file and the
# source cache.
SOURCE_ENV_UBUNTU_ISO="${UBUNTU_ISO+x}";     SOURCE_ENV_UBUNTU_ISO_VALUE="${UBUNTU_ISO-}"
SOURCE_ENV_CHEF360_INSTALLER_SOURCE="${CHEF360_INSTALLER_SOURCE+x}"; SOURCE_ENV_CHEF360_INSTALLER_SOURCE_VALUE="${CHEF360_INSTALLER_SOURCE-}"
SOURCE_ENV_CHEF360_LICENSE_SOURCE="${CHEF360_LICENSE_SOURCE+x}"; SOURCE_ENV_CHEF360_LICENSE_SOURCE_VALUE="${CHEF360_LICENSE_SOURCE-}"
SOURCE_ENV_CHEF360_TLS_CERT="${CHEF360_TLS_CERT+x}"; SOURCE_ENV_CHEF360_TLS_CERT_VALUE="${CHEF360_TLS_CERT-}"
SOURCE_ENV_CHEF360_TLS_KEY="${CHEF360_TLS_KEY+x}"; SOURCE_ENV_CHEF360_TLS_KEY_VALUE="${CHEF360_TLS_KEY-}"
SOURCE_ENV_CHEF360_TLS_CHAIN="${CHEF360_TLS_CHAIN+x}"; SOURCE_ENV_CHEF360_TLS_CHAIN_VALUE="${CHEF360_TLS_CHAIN-}"
SOURCE_ENV_CHEF360_ISSUING_CA="${CHEF360_ISSUING_CA+x}"; SOURCE_ENV_CHEF360_ISSUING_CA_VALUE="${CHEF360_ISSUING_CA-}"
SOURCE_ENV_CHEF360_ROOT_CA="${CHEF360_ROOT_CA+x}"; SOURCE_ENV_CHEF360_ROOT_CA_VALUE="${CHEF360_ROOT_CA-}"

if [[ -f "${KVM_STATE_FILE}" ]]; then
  # The state file is generated by this project and contains non-secret paths and VM metadata.
  # shellcheck disable=SC1090
  source "${KVM_STATE_FILE}"
fi

# Restore explicit environment values that the state file would otherwise shadow.
[[ -z "${SOURCE_ENV_UBUNTU_ISO}" ]] || UBUNTU_ISO="${SOURCE_ENV_UBUNTU_ISO_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_INSTALLER_SOURCE}" ]] || CHEF360_INSTALLER_SOURCE="${SOURCE_ENV_CHEF360_INSTALLER_SOURCE_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_LICENSE_SOURCE}" ]] || CHEF360_LICENSE_SOURCE="${SOURCE_ENV_CHEF360_LICENSE_SOURCE_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_TLS_CERT}" ]] || CHEF360_TLS_CERT="${SOURCE_ENV_CHEF360_TLS_CERT_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_TLS_KEY}" ]] || CHEF360_TLS_KEY="${SOURCE_ENV_CHEF360_TLS_KEY_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_TLS_CHAIN}" ]] || CHEF360_TLS_CHAIN="${SOURCE_ENV_CHEF360_TLS_CHAIN_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_ISSUING_CA}" ]] || CHEF360_ISSUING_CA="${SOURCE_ENV_CHEF360_ISSUING_CA_VALUE}"
[[ -z "${SOURCE_ENV_CHEF360_ROOT_CA}" ]] || CHEF360_ROOT_CA="${SOURCE_ENV_CHEF360_ROOT_CA_VALUE}"

# Optional local source cache. When set to a directory that already contains the
# matching artifact, builds prefer it over the default /install paths. Set
# KVM_SOURCE_DIR to point at a maintained cache such as ~/repos/sources.
KVM_SOURCE_DIR="${KVM_SOURCE_DIR:-}"

VM_NAME="${VM_NAME:-40_chef360}"
VM_HOSTNAME="${VM_HOSTNAME:-chef360-2.demo.lab}"
VM_SHORT_HOSTNAME="${VM_SHORT_HOSTNAME:-chef360-2}"
VM_IP="${VM_IP:-10.0.0.40}"
VM_PREFIX="${VM_PREFIX:-24}"
VM_GATEWAY="${VM_GATEWAY:-10.0.0.1}"
VM_DNS="${VM_DNS:-10.0.0.1}"
KVM_HOST_IP="${KVM_HOST_IP:-10.0.0.1}"
KVM_HOST_FQDN="${KVM_HOST_FQDN:-fury.demo.lab}"
AUTOMATE_IP="${AUTOMATE_IP:-10.0.0.21}"
AUTOMATE_FQDN="${AUTOMATE_FQDN:-automate.demo.lab}"
NODE1_IP="${NODE1_IP:-10.0.0.31}"
NODE1_FQDN="${NODE1_FQDN:-node1.demo.lab}"
NODE2_IP="${NODE2_IP:-10.0.0.32}"
NODE2_FQDN="${NODE2_FQDN:-node2.demo.lab}"
VM_NETWORK="${VM_NETWORK:-default}"
VM_MAC="${VM_MAC:-52:54:00:40:00:40}"
VM_MEMORY_MIB="${VM_MEMORY_MIB:-32768}"
VM_VCPUS="${VM_VCPUS:-16}"
VM_CPU_SHARES="${VM_CPU_SHARES:-2048}"
VM_OS_DISK_GIB="${VM_OS_DISK_GIB:-50}"
VM_DATA_DISK_GIB="${VM_DATA_DISK_GIB:-250}"
VM_DISK_PREALLOCATION="${VM_DISK_PREALLOCATION:-falloc}"
VM_OS_DISK_SERIAL="${VM_OS_DISK_SERIAL:-CHEF360_OS}"
VM_DATA_DISK_SERIAL="${VM_DATA_DISK_SERIAL:-CHEF360_DATA}"
VM_USER="${VM_USER:-chef}"
SSH_PRIVATE_KEY="${SSH_PRIVATE_KEY:-${HOME}/.ssh/fury_rsa}"
SSH_PUBLIC_KEY="${SSH_PUBLIC_KEY:-${HOME}/.ssh/fury_rsa.pub}"
UBUNTU_ISO="${UBUNTU_ISO:-/install/ubuntu/ubuntu-24.04.4-live-server-amd64.iso}"
LIBVIRT_POOL="${LIBVIRT_POOL:-default}"
LIBVIRT_URI="${LIBVIRT_URI:-qemu:///system}"
LIBVIRT_IMAGE_DIR="${LIBVIRT_IMAGE_DIR:-/var/lib/libvirt/images}"
OS_DISK="${OS_DISK:-${LIBVIRT_IMAGE_DIR}/${VM_NAME}-os.qcow2}"
DATA_DISK="${DATA_DISK:-${LIBVIRT_IMAGE_DIR}/${VM_NAME}-data.qcow2}"
KVM_WORK_DIR="${KVM_WORK_DIR:-${PROJECT_ROOT}/.kvm/${VM_NAME}}"
SEED_ISO="${SEED_ISO:-${KVM_WORK_DIR}/${VM_NAME}-seed.iso}"
INSTALL_KERNEL="${INSTALL_KERNEL:-${KVM_WORK_DIR}/vmlinuz}"
INSTALL_INITRD="${INSTALL_INITRD:-${KVM_WORK_DIR}/initrd}"
LIBVIRT_SEED_ISO="${LIBVIRT_SEED_ISO:-${LIBVIRT_IMAGE_DIR}/${VM_NAME}-seed.iso}"
LIBVIRT_INSTALL_KERNEL="${LIBVIRT_INSTALL_KERNEL:-${LIBVIRT_IMAGE_DIR}/${VM_NAME}-vmlinuz}"
LIBVIRT_INSTALL_INITRD="${LIBVIRT_INSTALL_INITRD:-${LIBVIRT_IMAGE_DIR}/${VM_NAME}-initrd}"
CHEF360_CONFIG_TEMPLATE="${CHEF360_CONFIG_TEMPLATE:-${PROJECT_ROOT}/knowledge-set/chef360-1.7.3/examples/kots-config.yaml}"
CHEF360_CONFIG_FILE="${CHEF360_CONFIG_FILE:-${KVM_WORK_DIR}/chef-config.yaml}"
CHEF360_SECRETS_FILE="${CHEF360_SECRETS_FILE:-${KVM_WORK_DIR}/chef360-secrets.env}"
CHEF360_TLS_CERT="${CHEF360_TLS_CERT:-${HOME}/certs/chef360-2.crt}"
CHEF360_TLS_KEY="${CHEF360_TLS_KEY:-${HOME}/certs/chef360-2.key}"
CHEF360_TLS_CHAIN="${CHEF360_TLS_CHAIN:-${HOME}/certs/chef360-2.chain.crt}"
CHEF360_ISSUING_CA="${CHEF360_ISSUING_CA:-${HOME}/certs/chef360-2_ica.crt}"
CHEF360_ROOT_CA="${CHEF360_ROOT_CA:-${HOME}/certs/chef360-2_rca.crt}"
CHEF360_INSTALLER_SOURCE="${CHEF360_INSTALLER_SOURCE:-/install/chef-360/1.7/chef-360}"
CHEF360_LICENSE_SOURCE="${CHEF360_LICENSE_SOURCE:-/install/chef-360/1.7/license.yaml}"
CHEF360_STAGE_DIR="${CHEF360_STAGE_DIR:-${KVM_WORK_DIR}/stage}"
CHEF360_STAGE_MANIFEST="${CHEF360_STAGE_MANIFEST:-${CHEF360_STAGE_DIR}/MANIFEST.txt}"

# Resolve an input artifact from the source cache when KVM_SOURCE_DIR names a
# directory that already holds the file. Explicit environment values win.
resolve_source() {
  local variable="$1" explicit_marker="$2" relative_path="$3" candidate
  [[ -n "${KVM_SOURCE_DIR}" ]] || return 0
  [[ -z "${explicit_marker}" ]] || return 0
  candidate="${KVM_SOURCE_DIR}/${relative_path}"
  [[ -e "${candidate}" ]] || return 0
  printf -v "${variable}" '%s' "${candidate}"
}

resolve_source UBUNTU_ISO "${SOURCE_ENV_UBUNTU_ISO}" "ubuntu/$(basename "${UBUNTU_ISO}")"
resolve_source CHEF360_INSTALLER_SOURCE "${SOURCE_ENV_CHEF360_INSTALLER_SOURCE}" "chef360/chef-360"
resolve_source CHEF360_LICENSE_SOURCE "${SOURCE_ENV_CHEF360_LICENSE_SOURCE}" "chef360/license.yaml"
resolve_source CHEF360_TLS_CERT "${SOURCE_ENV_CHEF360_TLS_CERT}" "chef360/tls/chef360-2.crt"
resolve_source CHEF360_TLS_KEY "${SOURCE_ENV_CHEF360_TLS_KEY}" "chef360/tls/chef360-2.key"
resolve_source CHEF360_TLS_CHAIN "${SOURCE_ENV_CHEF360_TLS_CHAIN}" "chef360/tls/chef360-2_chain.crt"
resolve_source CHEF360_ISSUING_CA "${SOURCE_ENV_CHEF360_ISSUING_CA}" "chef360/tls/chef360-2_ica.crt"
resolve_source CHEF360_ROOT_CA "${SOURCE_ENV_CHEF360_ROOT_CA}" "chef360/tls/chef360-2_rca.crt"

log_step() {
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"
}

fail() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || fail "Required command not found: $1"
}

require_file() {
  [[ -f "$1" ]] || fail "Required file not found: $1"
}

virsh_system() {
  virsh --connect "${LIBVIRT_URI}" "$@"
}

vm_exists() {
  virsh_system dominfo "${VM_NAME}" >/dev/null 2>&1
}

