# Resolve an input artifact from the source cache when KVM_SOURCE_DIR names a
# directory that already holds the file. Explicit environment values win.
resolve_source() {
  local variable="$1" explicit_marker="$2" relative_path="$3" candidate
  [[ -n "${KVM_SOURCE_DIR}" ]] || return 0
  [[ -z "${explicit_marker}" ]] || return 0
  candidate="${KVM_SOURCE_DIR}/${relative_path}"
  [[ -e "${candidate}" ]] || return 0
  printf -v "${variable}" '%s' "${candidate}"
}

